-- =====================================================================
-- Bond Budget — envelope app migration (replaces the monthly budget model)
-- =====================================================================
-- Run ONCE in the Supabase SQL editor: paste the whole file, click Run.
--
-- It runs as a single transaction. If you see ANY error, nothing was
-- changed — copy the error message and fix/retry before going further.
--
-- What it does:
--   1. Moves every old-model table into a hidden "old_budget" schema
--      (not deleted, not reachable from the app). Drop it later with:
--          drop schema old_budget cascade;
--   2. Keeps the bank-account list (renamed account -> accounts) so the
--      Plaid account links survive.
--   3. Creates the envelope tables and seeds 24 envelopes from the old
--      categories (latest monthly amount -> refill amount,
--      ROLLOVER -> rollover, RESET -> non-rollover). Balances start at $0.
--   4. Clears the Plaid sync cursors so the next sync re-reads history
--      (only transactions on/after the import start date are kept).
--   5. Adds the server-side functions the app calls (assign, split,
--      exclude, refill, undo refill, set balance, move money...).
--
-- Sign convention used everywhere in this app:
--   transactions.amount  > 0  money IN  (income, refunds)
--   transactions.amount  < 0  money OUT (purchases)
--   (Plaid's own convention is the opposite; the sync function flips it.)
-- Envelope balance = sum(allocations.amount) + sum(adjustments.amount)
-- =====================================================================

begin;

do $$
begin
  if to_regclass('public.envelopes') is not null then
    raise exception 'Migration already applied (public.envelopes exists). Nothing changed.';
  end if;
end $$;

-- ---------------------------------------------------------------------
-- 1. Park the old model in old_budget
-- ---------------------------------------------------------------------
create schema old_budget;

do $$
declare
  t text;
begin
  foreach t in array array[
    'disposition', 'month_status', 'category_month', 'recurring_allocation_rule',
    'planned_income_month', 'planned_income_rule', 'transaction_category_line',
    'merchant_category_rule', 'transaction', 'audit_log', 'category', 'category_group'
  ] loop
    if to_regclass(format('public.%I', t)) is not null then
      execute format('alter table public.%I set schema old_budget', t);
    end if;
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- 2. Accounts (kept; Plaid account ids preserved)
-- ---------------------------------------------------------------------
alter table public.account rename to accounts;
alter table public.accounts drop column if exists is_designated_savings_account;
alter table public.accounts drop column if exists is_tracked_credit_card;

-- Old categories pointed at the account table; that link is meaningless now.
alter table old_budget.category drop column if exists designated_savings_account_id;

-- ---------------------------------------------------------------------
-- 3. Settings
-- ---------------------------------------------------------------------
create table public.app_settings (
  id int primary key default 1 check (id = 1),
  import_start_date date not null
);
insert into public.app_settings (id, import_start_date) values (1, '2026-12-01');

-- ---------------------------------------------------------------------
-- 4. Envelopes
-- ---------------------------------------------------------------------
create table public.envelopes (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) > 0),
  sort_order int not null default 0,
  refill_amount numeric(12,2) not null default 0 check (refill_amount >= 0),
  rollover boolean not null default false,
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

insert into public.envelopes (name, sort_order, refill_amount, rollover, archived)
select
  c.name,
  row_number() over (order by g.sort_order, c.id),
  coalesce(r.amount, 0),
  c.rollover_behavior::text = 'ROLLOVER',
  not c.active
from old_budget.category c
join old_budget.category_group g on g.id = c.group_id
left join lateral (
  select rr.amount
  from old_budget.recurring_allocation_rule rr
  where rr.category_id = c.id
  order by rr.effective_start_month desc, rr.id desc
  limit 1
) r on true;

-- ---------------------------------------------------------------------
-- 5. Transactions (from Plaid) and their envelope allocations
-- ---------------------------------------------------------------------
create table public.transactions (
  id bigint generated by default as identity primary key,
  plaid_transaction_id text not null unique,
  pending_transaction_id text,              -- on a posted row: the pending row it replaced
  account_id bigint not null references public.accounts(id),
  txn_date date not null,                   -- purchase (authorized) date when Plaid has it, else posted date
  posted_date date,
  name text,                                -- raw bank description
  merchant_name text,                       -- Plaid's cleaned merchant name
  amount numeric(12,2) not null,            -- + in, - out
  pending boolean not null default false,
  status text not null default 'unassigned' check (status in ('unassigned', 'assigned', 'excluded')),
  attention text,                           -- e.g. 'Amount changed by bank' / 'Removed by bank'
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index transactions_status_date on public.transactions (status, txn_date desc);
create index transactions_date on public.transactions (txn_date desc);

create table public.allocations (
  id bigint generated by default as identity primary key,
  transaction_id bigint not null references public.transactions(id) on delete cascade,
  envelope_id bigint not null references public.envelopes(id),
  amount numeric(12,2) not null
);
create index allocations_envelope on public.allocations (envelope_id);
create index allocations_transaction on public.allocations (transaction_id);

-- ---------------------------------------------------------------------
-- 6. Refills and manual adjustments
-- ---------------------------------------------------------------------
create table public.refills (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  undone_at timestamptz
);

create table public.adjustments (
  id bigint generated by default as identity primary key,
  envelope_id bigint not null references public.envelopes(id),
  amount numeric(12,2) not null,
  kind text not null check (kind in ('manual', 'set_balance', 'move', 'refill')),
  note text,
  adj_date date not null default current_date,
  refill_id bigint references public.refills(id),
  move_group uuid,
  created_at timestamptz not null default now()
);
create index adjustments_envelope on public.adjustments (envelope_id);
create index adjustments_refill on public.adjustments (refill_id);

-- ---------------------------------------------------------------------
-- 7. Sync bookkeeping
-- ---------------------------------------------------------------------
delete from public.plaid_sync_cursor;

create table public.sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  trigger text not null,
  ok boolean,
  result jsonb
);

-- ---------------------------------------------------------------------
-- 8. Envelope balances (always computed, never stored)
-- ---------------------------------------------------------------------
create view public.envelope_balances with (security_invoker = true) as
select
  e.id, e.name, e.sort_order, e.refill_amount, e.rollover, e.archived,
  (coalesce(a.total, 0) + coalesce(j.total, 0))::numeric(12,2) as balance
from public.envelopes e
left join (select envelope_id, sum(amount) as total from public.allocations group by envelope_id) a on a.envelope_id = e.id
left join (select envelope_id, sum(amount) as total from public.adjustments group by envelope_id) j on j.envelope_id = e.id;

-- ---------------------------------------------------------------------
-- 9. Functions the app calls (all-or-nothing, validated server-side)
-- ---------------------------------------------------------------------
create or replace function public.envelope_balance(p_envelope_id bigint)
returns numeric language sql stable as $$
  select (coalesce((select sum(amount) from public.allocations where envelope_id = p_envelope_id), 0)
        + coalesce((select sum(amount) from public.adjustments where envelope_id = p_envelope_id), 0))::numeric(12,2);
$$;

-- p_lines: [{"envelope_id": 3, "amount": -45.12}, ...]  amounts must sum to the transaction amount.
create or replace function public.assign_transaction(p_transaction_id bigint, p_lines jsonb)
returns void language plpgsql as $$
declare
  t public.transactions;
  v_total numeric(12,2);
begin
  select * into t from public.transactions where id = p_transaction_id for update;
  if not found then raise exception 'Transaction not found'; end if;
  if t.pending then raise exception 'Pending transactions can be assigned once they post'; end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Pick at least one envelope';
  end if;
  if exists (select 1 from jsonb_array_elements(p_lines) l where (l->>'amount')::numeric(12,2) = 0) then
    raise exception 'Split amounts cannot be zero';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_lines) l
    left join public.envelopes e on e.id = (l->>'envelope_id')::bigint
    where e.id is null or e.archived
  ) then
    raise exception 'Envelope not found or archived';
  end if;

  select sum((l->>'amount')::numeric(12,2)) into v_total from jsonb_array_elements(p_lines) l;
  if v_total <> t.amount then
    raise exception 'Split adds up to %, but the transaction is %', v_total, t.amount;
  end if;

  delete from public.allocations where transaction_id = t.id;
  insert into public.allocations (transaction_id, envelope_id, amount)
  select t.id, (l->>'envelope_id')::bigint, (l->>'amount')::numeric(12,2)
  from jsonb_array_elements(p_lines) l;

  update public.transactions set status = 'assigned', attention = null, updated_at = now() where id = t.id;
end $$;

-- p_status: 'unassigned' (back to the inbox / restore) or 'excluded'
create or replace function public.set_transaction_status(p_transaction_id bigint, p_status text)
returns void language plpgsql as $$
declare
  t public.transactions;
begin
  if p_status not in ('unassigned', 'excluded') then raise exception 'Invalid status %', p_status; end if;
  select * into t from public.transactions where id = p_transaction_id for update;
  if not found then raise exception 'Transaction not found'; end if;
  if t.pending then raise exception 'Pending transactions can be changed once they post'; end if;

  delete from public.allocations where transaction_id = t.id;
  update public.transactions
     set status = p_status,
         attention = case when p_status = 'excluded' then null else attention end,
         updated_at = now()
   where id = t.id;
end $$;

create or replace function public.set_envelope_balance(p_envelope_id bigint, p_new_balance numeric, p_note text default null, p_date date default current_date)
returns void language plpgsql as $$
declare
  v_diff numeric(12,2);
begin
  perform 1 from public.envelopes where id = p_envelope_id;
  if not found then raise exception 'Envelope not found'; end if;
  v_diff := round(p_new_balance, 2) - public.envelope_balance(p_envelope_id);
  if v_diff <> 0 then
    insert into public.adjustments (envelope_id, amount, kind, note, adj_date)
    values (p_envelope_id, v_diff, 'set_balance', nullif(trim(p_note), ''), coalesce(p_date, current_date));
  end if;
end $$;

create or replace function public.add_adjustment(p_envelope_id bigint, p_amount numeric, p_note text default null, p_date date default current_date)
returns void language plpgsql as $$
begin
  if round(p_amount, 2) = 0 then raise exception 'Amount cannot be zero'; end if;
  insert into public.adjustments (envelope_id, amount, kind, note, adj_date)
  values (p_envelope_id, round(p_amount, 2), 'manual', nullif(trim(p_note), ''), coalesce(p_date, current_date));
end $$;

create or replace function public.move_money(p_from bigint, p_to bigint, p_amount numeric, p_note text default null, p_date date default current_date)
returns void language plpgsql as $$
declare
  g uuid := gen_random_uuid();
  v_from text;
  v_to text;
begin
  if p_from = p_to then raise exception 'Pick two different envelopes'; end if;
  if round(p_amount, 2) <= 0 then raise exception 'Amount must be more than zero'; end if;
  select name into v_from from public.envelopes where id = p_from;
  select name into v_to from public.envelopes where id = p_to;
  if v_from is null or v_to is null then raise exception 'Envelope not found'; end if;
  insert into public.adjustments (envelope_id, amount, kind, note, adj_date, move_group) values
    (p_from, -round(p_amount, 2), 'move', coalesce(nullif(trim(p_note), ''), 'Moved to ' || v_to), coalesce(p_date, current_date), g),
    (p_to,    round(p_amount, 2), 'move', coalesce(nullif(trim(p_note), ''), 'Moved from ' || v_from), coalesce(p_date, current_date), g);
end $$;

-- Deletes a manual / set-balance adjustment, or both halves of a move.
-- Refill lines are removed only by undoing the whole refill.
create or replace function public.delete_adjustment(p_adjustment_id bigint)
returns void language plpgsql as $$
declare
  a public.adjustments;
begin
  select * into a from public.adjustments where id = p_adjustment_id;
  if not found then raise exception 'Adjustment not found'; end if;
  if a.kind = 'refill' then raise exception 'Refill entries are removed with "Undo refill"'; end if;
  if a.move_group is not null then
    delete from public.adjustments where move_group = a.move_group;
  else
    delete from public.adjustments where id = a.id;
  end if;
end $$;

-- Refill: rollover envelopes get +refill_amount; non-rollover envelopes are
-- set to exactly refill_amount (leftover or deficit disappears). Archived
-- envelopes are skipped. Returns the refill id.
create or replace function public.do_refill(p_date date default current_date)
returns bigint language plpgsql as $$
declare
  v_refill_id bigint;
begin
  -- Guard against a double tap: refuse a second refill within 10 seconds.
  if exists (select 1 from public.refills where undone_at is null and created_at > now() - interval '10 seconds') then
    raise exception 'A refill was just applied';
  end if;

  insert into public.refills default values returning id into v_refill_id;

  insert into public.adjustments (envelope_id, amount, kind, note, adj_date, refill_id)
  select id, delta, 'refill', 'Refill', coalesce(p_date, current_date), v_refill_id
  from (
    select b.id,
           case when b.rollover then b.refill_amount else b.refill_amount - b.balance end::numeric(12,2) as delta
    from public.envelope_balances b
    where not b.archived
  ) x
  where delta <> 0;

  return v_refill_id;
end $$;

create or replace function public.undo_refill(p_refill_id bigint)
returns void language plpgsql as $$
begin
  update public.refills set undone_at = now() where id = p_refill_id and undone_at is null;
  if not found then raise exception 'That refill was already undone'; end if;
  delete from public.adjustments where refill_id = p_refill_id;
end $$;

-- p_ids: envelope ids in the desired display order.
create or replace function public.reorder_envelopes(p_ids bigint[])
returns void language sql as $$
  update public.envelopes e set sort_order = x.ord
  from unnest(p_ids) with ordinality as x(id, ord)
  where e.id = x.id;
$$;

